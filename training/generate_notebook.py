    "                nn.ConvTranspose2d(32, 1, 4, 2, 1), nn.Sigmoid()\n",
    "            )\n",
    "        def forward(self, pixel_values):\n",
    "            feats = self.encoder(pixel_values)\n",
    "            class Out: pass\n",
    "            out = Out()\n",
    "            out.predicted_depth = self.decoder(feats).squeeze(1)\n",
