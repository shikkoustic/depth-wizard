    "# 4. Enhanced Loss: Scale-Invariant Log + Gradient Smoothness + Tall Structure Focus\n",
    "class DepthWizardMultiLoss(nn.Module):\n",
    "    def __init__(self, alpha=3.0, lambda_grad=0.5):\n",
    "        super().__init__()\n",
    "        self.alpha = alpha\n",
    "        self.lambda_grad = lambda_grad\n",
    "        \n",
    "    def forward(self, pred, target):\n",
    "        valid = target > 0.1\n",
    "        if not torch.any(valid):\n",
    "            return torch.tensor(0.0, device=pred.device, requires_grad=True)\n",
    "            \n",
    "        p, t = pred[valid], target[valid]\n",
    "        d = torch.log(torch.clamp(p, min=0.1)) - torch.log(torch.clamp(t, min=0.1))\n",
    "        silog = torch.sqrt(torch.mean(d ** 2) - 0.5 * (torch.mean(d) ** 2))\n",
    "        \n",
    "        # Height-weighted L1 penalty\n",
    "        weights = 1.0 + self.alpha * torch.clamp(t / 25.0, 0.0, 3.5)\n",
    "        l1 = torch.mean(weights * torch.abs(p - t))\n",
    "        \n",
    "        return silog + 2.0 * l1\n",
    "\n",
    "# 5. Backbone Setup\n",
    "try:\n",
